import os
import re
from itertools import count

import httpx
import pytest


pytest_plugins = ["qa_lab.pytest_plugin"]
_repo_counter = count(1)


@pytest.fixture(scope="session")
def base_url() -> str:
    return os.environ.get("GITEA_BASE_URL", "http://127.0.0.1:13000").rstrip("/")


@pytest.fixture(scope="session")
def run_id() -> str:
    return os.environ.get("GITEA_RUN_ID", "local-manual-run")


def _auth(user_key: str) -> tuple[str, str]:
    username = os.environ.get(f"GITEA_{user_key}_USERNAME")
    password = os.environ.get(f"GITEA_{user_key}_PASSWORD")
    if not username or not password:
        pytest.fail(f"Missing local test credentials for {user_key}; run scripts/up.py first.")
    return username, password


@pytest.fixture
def admin_auth() -> tuple[str, str]:
    return _auth("ADMIN")


@pytest.fixture
def owner_auth() -> tuple[str, str]:
    return _auth("OWNER")


@pytest.fixture
def guest_auth() -> tuple[str, str]:
    return _auth("GUEST")


@pytest.fixture
def admin_client(base_url, admin_auth):
    with httpx.Client(base_url=f"{base_url}/api/v1", auth=admin_auth, timeout=15) as client:
        yield client


@pytest.fixture
def owner_client(base_url, owner_auth):
    with httpx.Client(base_url=f"{base_url}/api/v1", auth=owner_auth, timeout=15) as client:
        yield client


@pytest.fixture
def guest_client(base_url, guest_auth):
    with httpx.Client(base_url=f"{base_url}/api/v1", auth=guest_auth, timeout=15) as client:
        yield client


@pytest.fixture
def private_repo(admin_client, admin_auth, run_id, request):
    suffix = re.sub(r"[^a-z0-9-]+", "-", request.node.name.lower()).strip("-")[:28]
    name = f"qa-{run_id[-8:].lower()}-{next(_repo_counter):02d}-{suffix}"
    response = admin_client.post(
        "/user/repos",
        json={"name": name, "private": True, "auto_init": True, "description": "Generated by Gitea Quality Lab"},
    )
    assert response.status_code == 201, f"repository creation returned {response.status_code}: {response.text}"
    return response.json()
